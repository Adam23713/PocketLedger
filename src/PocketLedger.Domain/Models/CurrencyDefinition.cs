    private static readonly Dictionary<string, CurrencyDefinition> ByCode = All.ToDictionary(item => item.Code, StringComparer.OrdinalIgnoreCase);

    public static CurrencyDefinition Get(string? code) => code is not null && ByCode.TryGetValue(code.Trim(), out var definition)
        ? definition
        : throw new ArgumentException("Unsupported currency.", nameof(code));

    public static bool Exists(string? code) => code is not null && ByCode.ContainsKey(code.Trim());
